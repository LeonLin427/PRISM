"""Compute SDK attribution, stability, and descriptive case studies.

Inputs are the graph tables and the edge cache generated by load_data.
Outputs are out/sdk_attribution.xlsx and out/m4_report.md.

For each category, compute S_c[i]=(dT_c/dE_i) dot E_i, where T_c is the mean
logit among positive events and SDK embeddings follow sdk_names order.
Mean pairwise Spearman correlation across three seeds determines stability.
Use mean gradient scores when rho>=0.6; otherwise use deterministic frequency
difference, positive-event usage minus other-event usage. Save both score types.

Removal/addition relations encode retrospective information. Auxiliary SDK
notices are not aligned SDK-level ground truth, and remediation removal is not
independent validation of a graph that already contains removal relations.
Rankings and cases are descriptive, not external validation.

Attribution uses eval mode with dropout disabled and torch.enable_grad()."""
import argparse
import os
import time

import numpy as np
import pandas as pd
import torch
import scipy.stats as st

from gnn_model import RGCN
from train_gnn import load_data, build_subgraph, to_adjacency, train_gnn, \
    EDGE_TYPES, CLASSES, N_CLASSES
from match_sdks import load_signatures

HERE = os.path.dirname(os.path.abspath(__file__))
NODES_CSV = os.path.join(HERE, 'graph', 'nodes.csv')
REMEDIATION = os.path.join(HERE, 'remediation.csv')
OUT_XLSX = os.path.join(HERE, 'out', 'sdk_attribution.xlsx')
OUT_REPORT = os.path.join(HERE, 'out', 'm4_report.md')

# Prespecified thresholds, fixed rather than tuned on observed outcomes.
RHO_THRESHOLD = 0.6     # Minimum mean pairwise Spearman correlation for gradient-based rankings.
W = 1                    # All observed co-occurrence pairs (w>=1), matching the full RGCN.

CASE_APPS = ['吴试纸', '备忘录记事本', '健康界']  # Applications selected for descriptive case studies.


# --------------------------------------------------------------------------
# Attribution scores.
# --------------------------------------------------------------------------

def class_attribution(model, X_all, adj, Y, n_sdk):
    """Return an (n_sdk, 6) matrix of category-specific gradient-times-input scores.
    T_c is the mean logit among positive events. A batched vector-Jacobian product
    obtains all six gradients with grad_outputs[c][a,c]=1/|P_c| for a in P_c,
    and zero elsewhere. Rows follow sdk_names."""
    model.eval()
    n_app = X_all.shape[0]
    with torch.enable_grad():
        E = model.embed.weight                    # (n_nonapp, d_feat) Parameter
        logits = model(X_all, adj, torch.arange(n_app))  # (n_app, 6)
        V = torch.zeros((N_CLASSES, n_app, N_CLASSES))
        for c in range(N_CLASSES):
            P = np.where(Y[:, c] == 1)[0]
            if len(P) > 0:
                V[c, P, c] = 1.0 / len(P)
        G = torch.autograd.grad(logits, E, grad_outputs=V,
                                is_grads_batched=True)[0]  # (6, n_nonapp, d_feat)
        S = (G * E.unsqueeze(0)).sum(-1).detach().cpu().numpy()  # (6, n_nonapp)
    return S[:, :n_sdk].T                          # (n_sdk, 6)


def per_app_attribution(model, X_all, adj, app_idx, c, n_sdk):
    """Compute gradient-times-input on one event/category logit for a case study."""
    model.eval()
    with torch.enable_grad():
        logits = model(X_all, adj, torch.tensor([app_idx]))
        G = torch.autograd.grad(logits[0, c], model.embed.weight)[0]
        S = (G * model.embed.weight.detach()).sum(-1).cpu().numpy()
    return S[:n_sdk]


# --------------------------------------------------------------------------
# Stability assessment and deterministic fallback.
# --------------------------------------------------------------------------

def stability_and_fallback(scores_per_seed, sdk_mat, Y, rho_threshold):
    """Use mean gradient scores if mean cross-seed Spearman rho passes the gate;
    otherwise use deterministic frequency difference.
    Return final_scores of shape (n_sdk, 6), method[6], and rho[6]."""
    n_sdk = scores_per_seed[0].shape[0]
    rho = np.zeros(N_CLASSES)
    method = []
    final = np.zeros((n_sdk, N_CLASSES))
    n_seed = len(scores_per_seed)
    for c in range(N_CLASSES):
        vecs = [S[:, c] for S in scores_per_seed]
        cors = []
        for p in range(n_seed):
            for q in range(p + 1, n_seed):
                r = st.spearmanr(vecs[p], vecs[q]).correlation
                if not np.isnan(r):
                    cors.append(r)
        rho[c] = float(np.mean(cors)) if cors else 0.0
        if n_seed >= 2 and rho[c] >= rho_threshold:
            method.append('gradient')
            final[:, c] = np.mean(vecs, axis=0)
        elif n_seed >= 2:
            method.append('freqdiff')
            P = Y[:, c] == 1
            final[:, c] = sdk_mat[P].mean(0) - sdk_mat[~P].mean(0)
        else:  # A one-seed smoke test cannot assess stability; use its gradient scores directly.
            method.append('gradient')
            final[:, c] = np.mean(vecs, axis=0)
    return final, method, rho


# --------------------------------------------------------------------------
# Case studies.
# --------------------------------------------------------------------------

def split_removed(s):
    if s is None or (isinstance(s, float) and np.isnan(s)):
        return []
    return [x.strip() for x in str(s).split('；') if x.strip()]


def top_k_sdks(score, sdk_names, k=10):
    order = np.argsort(-score)[:k]
    return [(sdk_names[i], float(score[i])) for i in order]


# --------------------------------------------------------------------------
# Self-checks (--selfcheck).
# --------------------------------------------------------------------------

def determinism_check(model, X_all, adj):
    model.eval()
    with torch.no_grad():
        a = model(X_all, adj, torch.arange(X_all.shape[0]))
        b = model(X_all, adj, torch.arange(X_all.shape[0]))
    return bool(torch.allclose(a, b))


def finite_diff_check(model, X_all, adj, Y, n_sdk):
    """Check the top SDK by finite differences: perturb E_i by epsilon*E_i.
    The resulting change in T divided by epsilon should approximate S_i."""
    S = class_attribution(model, X_all, adj, Y, n_sdk)[:, 0]
    i = int(np.argmax(S))
    eps = 1e-3
    E0 = model.embed.weight.detach().clone()
    pos = torch.tensor(np.where(Y[:, 0] == 1)[0])
    model.eval()
    with torch.no_grad():
        T0 = model(X_all, adj, torch.arange(X_all.shape[0]))[pos, 0].mean().item()
        model.embed.weight.data[i] = E0[i] * (1 + eps)
        T1 = model(X_all, adj, torch.arange(X_all.shape[0]))[pos, 0].mean().item()
        model.embed.weight.data[i] = E0[i]
    ratio = (T1 - T0) / eps          # ΔE_i = eps*E_i → ΔT/eps ≈ G_i·E_i = S_i
    ok = np.sign(ratio) == np.sign(S[i]) and \
        abs(ratio - S[i]) / max(abs(S[i]), 1e-6) < 0.5
    return i, float(S[i]), ratio, bool(ok)


# --------------------------------------------------------------------------
# Main workflow.
# --------------------------------------------------------------------------

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--seeds', default='1000,2000,3000')
    ap.add_argument('--epochs', type=int, default=300)
    ap.add_argument('--lr', type=float, default=1e-3)
    ap.add_argument('--threads', type=int, default=1)
    ap.add_argument('--rho-threshold', type=float, default=RHO_THRESHOLD)
    ap.add_argument('--quick', action='store_true', help='Smoke test: one seed, 60 epochs')
    ap.add_argument('--nosdk-robustness', action='store_true',
                    help='Retrain without SDK co-occurrence and compare top-10 rankings')
    ap.add_argument('--selfcheck', action='store_true',
                    help='Check evaluation determinism and finite-difference attribution')
    args = ap.parse_args()
    torch.set_num_threads(max(1, args.threads))

    seeds = [int(s) for s in args.seeds.split(',')]
    if args.quick:
        seeds, epochs = seeds[:1], 60
    else:
        epochs = args.epochs

    (df, folders, static_cols, diff_cols, sdk_names, api_names, perm_names, Y,
     cache, diff_sdks) = load_data()
    n_app = len(folders)
    n_nonapp = len(sdk_names) + len(perm_names) + len(api_names)
    n_sdk = len(sdk_names)

    # Feature construction matches main CV; rows follow event-node order.
    feat_all = df[static_cols + diff_cols].to_numpy(float)
    mean = feat_all.mean(0)
    std = feat_all.std(0)
    std[std == 0] = 1.0
    feat_z = (feat_all - mean) / std
    print(f'数据: {n_app} App / SDK {n_sdk} 权限 {len(perm_names)} API {len(api_names)}'
          f' / 特征 {feat_z.shape[1]}')
    sdk_mat = df[[f'sdk_{n}' for n in sdk_names]].to_numpy(float)
    X_all = torch.tensor(feat_z, dtype=torch.float32)

    assert np.isfinite(feat_z).all(), 'feat_z 含 NaN/Inf'

    # Check embedding rows against nodes.csv to preserve SDK-name alignment.
    nodes = pd.read_csv(NODES_CSV, encoding='utf-8-sig')
    sdk_nodes = nodes[nodes['type'] == 'sdk']['name'].tolist()
    assert sdk_nodes == sdk_names, 'embedding 行序与 nodes.csv sdk 序不一致!'

    # Full difference-aware graph, including SDK removal/addition relations.
    n_nodes, edges = build_subgraph(folders, cache, sdk_names, api_names, perm_names, W,
                                    diff_sdks)
    adj = to_adjacency(n_nodes, edges)
    print(f'图: {n_nodes} 节点, {len(edges)} 边')

    sig_by_name = {s['name']: s for s in load_signatures()}

    # Fit an independent model and compute attribution for each seed.
    scores_per_seed, models = [], []
    t0 = time.time()
    for seed in seeds:
        torch.manual_seed(seed)
        model = RGCN(feat_z.shape[1], n_nonapp, len(EDGE_TYPES), N_CLASSES)
        train_gnn(model, X_all, adj, np.arange(n_app), Y, epochs, args.lr, seed)
        S = class_attribution(model, X_all, adj, Y, n_sdk)
        scores_per_seed.append(S)
        models.append(model)
        print(f'[seed {seed}] 训练+归因 {time.time()-t0:.0f}s')
    t0 = time.time()

    if args.selfcheck:
        m0 = models[0]
        det = determinism_check(m0, X_all, adj)
        i, S0, ratio, fok = finite_diff_check(m0, X_all, adj, Y, n_sdk)
        print(f'[selfcheck] eval 确定性 {det}; 有限差分 top-1 SDK={sdk_names[i]} '
              f'S={S0:.3f} ΔT/ε={ratio:.3f} 通过={fok}')
        assert det, 'eval 两遍前向不一致'
        assert fok, '有限差分未通过'

    final_scores, method, rho = stability_and_fallback(
        scores_per_seed, sdk_mat, Y, args.rho_threshold)
    print('稳定性: ' + ', '.join(f'{CLASSES[c]} ρ={rho[c]:.2f} {method[c]}'
                                 for c in range(N_CLASSES)))

    # Optional robustness check: retrain without SDK co-occurrence and compare top-10 lists.
    robust = None
    if args.nosdk_robustness:
        adj_ns = to_adjacency(n_nodes, edges, drop_edges=('sdk-sdk',))
        torch.manual_seed(seeds[0])
        m_ns = RGCN(feat_z.shape[1], n_nonapp, len(EDGE_TYPES), N_CLASSES)
        train_gnn(m_ns, X_all, adj_ns, np.arange(n_app), Y, epochs, args.lr, seeds[0])
        S_ns = class_attribution(m_ns, X_all, adj_ns, Y, n_sdk)
        base = np.mean(scores_per_seed, axis=0)
        robust = {
            'rho': [st.spearmanr(base[:, c], S_ns[:, c]).correlation
                    for c in range(N_CLASSES)],
            'overlap': [len(set(np.argsort(-base[:, c])[:10]) &
                              set(np.argsort(-S_ns[:, c])[:10]))
                        for c in range(N_CLASSES)],
        }
        print(f'[nosdk] top-10 重合(6 类) {robust["overlap"]}')

    # Descriptive cases juxtapose rankings with removals; overlap is not validation.
    remediation = pd.read_csv(REMEDIATION, encoding='utf-8-sig')
    rem_by_folder = {}
    for _, r in remediation.iterrows():
        rem_by_folder[f"{r['folder']}__{r.get('batch', '')}"] = r
    case_rows = []
    for name in CASE_APPS:
        # Process every matching event when an application has repeated notices.
        ev_folders = [i for i, f in enumerate(folders) if f.startswith(name + '__')]
        if not ev_folders:
            print(f'[个案] 跳过(不在语料中): {name}')
            continue
        for ai in ev_folders:
            app_classes = [c for c in range(N_CLASSES) if Y[ai, c] == 1]
            row = rem_by_folder.get(folders[ai])
            for c in app_classes:
                # Apply the category-level stability gate to cases: per-event gradients only if stable.
                # Otherwise use the category's final deterministic global frequency-difference ranking.
                if method[c] == 'gradient':
                    score = np.mean([per_app_attribution(m, X_all, adj, ai, c, n_sdk)
                                     for m in models], axis=0)
                    case_method = 'per-app gradient'
                else:
                    score = final_scores[:, c]
                    case_method = method[c]
                top10 = top_k_sdks(score, sdk_names, 10)
                removed = split_removed(row['removed_sdks']) if row is not None else []
                with torch.no_grad():
                    pred_prob = float(np.mean([
                        torch.sigmoid(m(X_all, adj, torch.tensor([ai]))[0, c]).item()
                        for m in models]))
                case_rows.append({
                    'app': name, 'class': CLASSES[c], 'label': 1.0,
                    'method': case_method,
                    'pred_prob': pred_prob,
                    'top10': '；'.join(s for s, _ in top10),
                    'removed_sdks': '；'.join(removed) or '(无)',
                    'n_removed_components': int(row['n_removed_components']) if row is not None else np.nan,
                })

    write_outputs(final_scores, method, rho, sdk_names, sdk_mat, Y, sig_by_name,
                  case_rows, robust, seeds, epochs, args)

    print(f'完成: {OUT_REPORT} + {OUT_XLSX}')


# --------------------------------------------------------------------------
# Output generation.
# --------------------------------------------------------------------------

def write_outputs(final_scores, method, rho, sdk_names, sdk_mat, Y, sig_by_name,
                  case_rows, robust, seeds, epochs, args):
    os.makedirs(os.path.join(HERE, 'out'), exist_ok=True)

    # Long-format category-specific SDK rankings.
    risk_rows = []
    for c in range(N_CLASSES):
        cc = CLASSES[c]
        P = Y[:, c] == 1
        usage_pos = sdk_mat[P].mean(0)
        usage_neg = sdk_mat[~P].mean(0)
        order = np.argsort(-final_scores[:, c])
        for rk, i in enumerate(order, 1):
            name = sdk_names[i]
            sig = sig_by_name.get(name, {})
            risk_rows.append({
                'class': cc, 'sdk': name, 'rank': rk,
                'score': final_scores[i, c],
                'freqdiff': usage_pos[i] - usage_neg[i],
                'usage_in_pos': usage_pos[i], 'usage_in_neg': usage_neg[i],
                'method': method[c], 'miit_flagged': bool(sig.get('miit_flagged', False)),
            })

    with pd.ExcelWriter(OUT_XLSX, engine='openpyxl') as w:
        pd.DataFrame(risk_rows).to_excel(w, sheet_name='per_class_risk', index=False)
        pd.DataFrame([{'class': CLASSES[c], 'rho': rho[c], 'method': method[c]}
                      for c in range(N_CLASSES)]).to_excel(
            w, sheet_name='stability', index=False)
        pd.DataFrame(case_rows).to_excel(w, sheet_name='case_studies', index=False)
        if robust is not None:
            pd.DataFrame([{'class': CLASSES[c], 'spearman': robust['rho'][c],
                           'top10_overlap': robust['overlap'][c]}
                          for c in range(N_CLASSES)]).to_excel(
                w, sheet_name='nosdk_robustness', index=False)

    # Human-readable report.
    L = []
    A = L.append
    A('# SDK attribution and descriptive case studies')
    A('')
    A(f'- Model: full-graph RGCN fitted to all corpus events, with the same hyperparameters as gnn_full: lr={args.lr}, '
      f'epochs={epochs}, seeds {seeds}.')
    A('- Difference-aware graph: app-removed-sdk/app-added-sdk relations encode retrospective '
      'remediated-version information; rankings reflect both SDK use and remediation evidence.')
    A('- Attribution: SDK embedding gradient times input, S_c[i]=(∂T_c/∂E_i)·E_i; '
      'T_c is the mean logit among category-positive events.')
    A('- Prespecified gate: use gradient rankings when category-level ρ_c, the mean pairwise '
      'Spearman correlation across 3 seeds, is >= 0.6; otherwise use deterministic frequency '
      'difference. Both score types are retained.')
    A('- External validity and recall@K are not evaluated: application and SDK notices have '
      'different scopes and timing, and remediation removals are not independent ground truth '
      'when removal relations are already graph inputs.')
    A('')
    A('## Cross-seed stability (3 seeds)')
    A('')
    A('| class | rho | method |')
    A('|---|---|---|')
    for c in range(N_CLASSES):
        A(f'| {CLASSES[c]} | {rho[c]:.3f} | {method[c]} |')
    A('')
    A('## Top-10 SDKs per category, ranked by the selected method')
    A('')
    for c in range(N_CLASSES):
        cc = CLASSES[c]
        order = np.argsort(-final_scores[:, c])[:10]
        A(f'### {cc} (method={method[c]})')
        A('')
        A('| rank | sdk | score | freqdiff | flagged |')
        A('|---|---|---|---|---|')
        for rk, i in enumerate(order, 1):
            sig = sig_by_name.get(sdk_names[i], {})
            A(f'| {rk} | {sdk_names[i]} | {final_scores[i, c]:.4f} '
              f'| {sdk_mat[Y[:, c] == 1].mean(0)[i] - sdk_mat[Y[:, c] == 0].mean(0)[i]:.3f} '
              f'| {"✓" if sig.get("miit_flagged") else ""} |')
        A('')
    A('## Descriptive cases: top-10 rankings alongside remediation removals')
    A('')
    for r in case_rows:
        A(f"### {r['app']} ({r['class']}, method={r['method']}; "
          f"in-sample descriptive score={r['pred_prob']:.3f})")
        A('- This score comes from a full-corpus fit and describes the case; it is not an OOF prediction or a generalization estimate.')
        A('')
        A(f"- Top-10 SDKs for this category: {r['top10']}")
        A(f"- SDKs removed during remediation: {r['removed_sdks']}")
        A(f"- Number of removed components: {r['n_removed_components']}")
        A('')
    if robust is not None:
        A('## Robustness: retraining without SDK co-occurrence (1 seed)')
        A('')
        A('| class | spearman | top10_overlap |')
        A('|---|---|---|')
        for c in range(N_CLASSES):
            A(f'| {CLASSES[c]} | {robust["rho"][c]:.3f} | {robust["overlap"][c]}/10 |')
        A('')
    A('## Interpretation and limitations')
    A('')
    A('- Attribution depends on the full graph through 2 layers of relational aggregation, '
      'including SDK co-occurrence. It provides rankings, not per-edge causal effects.')
    A('- Gradient times input is a local first-order measure assessed for cross-seed stability; '
      'the rankings are descriptive profiles, not detectors.')
    A('- Removal/addition relations directly encode retrospective remediation evidence. '
      'Frequency difference compares category-positive and other events, independently of auxiliary SDK-list membership.')
    A('- The differences in remediation.csv are retrospective evidence, distinct from prospective prediction.')
    A('- Cases are illustrative examples selected after analysis. Categories below the stability gate use '
      'the global frequency-difference ranking; case overlap is not external validation or causal evidence.')
    with open(OUT_REPORT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(L) + '\n')


if __name__ == '__main__':
    main()
